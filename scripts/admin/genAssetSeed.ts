import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SKIN_CATALOG, ACCESSORY_CATALOG } from '../../src/data/shopCatalog';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..', '..');
const OUT_FILE = path.join(ROOT, 'supabase', 'seed_assets.sql');

function escapeSql(str: string): string {
  return str.replace(/'/g, "''");
}

function generateSeed(): void {
  const rows: { id: string; asset_type: string; name: string }[] = [
    { id: 'crystals', asset_type: 'crystals', name: 'Crystals' },
    { id: 'stardust', asset_type: 'stardust', name: 'Stardust' },
    { id: 'shields', asset_type: 'shields', name: 'Shields' },
  ];

  for (const skin of SKIN_CATALOG) {
    rows.push({
      id: skin.id,
      asset_type: 'skin',
      name: skin.name,
    });
  }

  for (const acc of ACCESSORY_CATALOG) {
    rows.push({
      id: acc.id,
      asset_type: 'accessory',
      name: acc.name,
    });
  }

  const valuesSql = rows
    .map(
      (r) =>
        `  ('${escapeSql(r.id)}', '${escapeSql(r.asset_type)}', '${escapeSql(r.name)}')`,
    )
    .join(',\n');

  const sql = `-- Generated by scripts/admin/genAssetSeed.ts. Paste into Supabase SQL Editor.
-- Populates all known skins, accessories, and currencies so coupon and reward FKs are validated.

insert into public.game_assets (id, asset_type, name) values
${valuesSql}
on conflict (id) do update set
  asset_type = excluded.asset_type,
  name = excluded.name;
`;

  writeFileSync(OUT_FILE, sql, 'utf-8');
  console.log(`✓ Wrote ${rows.length} game assets to ${OUT_FILE}`);
}

generateSeed();
