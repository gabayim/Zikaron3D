"""Synthesizes Beat Circuit's instrument with ffmpeg: glassy bell notes MIDI 57..84 (A3..C6) plus the
beat bed (kick, hat, count-in tick) and a miss buzz, into assets/audio/notes/*.m4a. Writes the static
require map src/fx/noteRegistry.ts. Everything is generated here; no recordings or samples are used.

    python scripts/assets/buildNotes.py
"""
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "assets" / "audio" / "notes"
REGISTRY = ROOT / "src" / "fx" / "noteRegistry.ts"
LOW, HIGH = 57, 84


def synth(name: str, dur: float, expr: str, extra_af: str = "") -> None:
    af = f"afade=t=in:d=0.004,afade=t=out:st={dur - 0.04:.3f}:d=0.04"
    if extra_af:
        af = f"{extra_af},{af}"
    af += ",alimiter=limit=0.9"
    subprocess.run(
        [
            "ffmpeg", "-y", "-v", "error",
            "-f", "lavfi", "-i", f"aevalsrc='{expr}':s=44100:d={dur}",
            "-af", af,
            "-c:a", "aac", "-b:a", "96k",
            str(OUT / f"{name}.m4a"),
        ],
        check=True,
    )


def bell(freq: float) -> str:
    # Two-operator FM bell: bright strike that mellows into a pure tone, plus a soft octave shimmer.
    return (
        f"0.55*sin(2*PI*{freq:.4f}*t+1.6*exp(-7*t)*sin(2*PI*{freq * 2:.4f}*t))*exp(-2.6*t)"
        f"+0.12*sin(2*PI*{freq * 2:.4f}*t)*exp(-5*t)"
    )


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for midi in range(LOW, HIGH + 1):
        freq = 440.0 * 2 ** ((midi - 69) / 12)
        synth(f"n{midi}", 1.6, bell(freq))
        print(f"n{midi} {freq:.1f}Hz")
    synth("kick", 0.32, "0.95*sin(2*PI*(50*t+3.2*(1-exp(-28*t))))*exp(-9*t)")
    synth("hat", 0.07, "0.5*(random(0)*2-1)*exp(-60*t)", "highpass=f=7000")
    synth("tick", 0.08, "0.5*sin(2*PI*1760*t)*exp(-45*t)")
    synth("buzz", 0.26, "0.35*(gte(sin(2*PI*98*t),0)*2-1)*exp(-7*t)", "lowpass=f=900")

    lines = [
        "// Generated by scripts/assets/buildNotes.py. Do not edit by hand.",
        "",
        f"export const NOTE_LOW = {LOW};",
        f"export const NOTE_HIGH = {HIGH};",
        "",
        "export const NOTE_SOURCES: Record<number, number> = {",
    ]
    for midi in range(LOW, HIGH + 1):
        lines.append(f"  {midi}: require('../../assets/audio/notes/n{midi}.m4a'),")
    lines += [
        "};",
        "",
        "export const BEAT_SOURCES = {",
        "  kick: require('../../assets/audio/notes/kick.m4a'),",
        "  hat: require('../../assets/audio/notes/hat.m4a'),",
        "  tick: require('../../assets/audio/notes/tick.m4a'),",
        "  buzz: require('../../assets/audio/notes/buzz.m4a'),",
        "} as const;",
        "",
    ]
    REGISTRY.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {REGISTRY.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
